const notion = new Client({ auth: NOTION_TOKEN });

async function addRecord(name) {
  return notion.pages.create({
    parent: { database_id: DATABASE_ID },
    properties: {
      [TITLE_PROPERTY]: {
        title: [
          {
            text: { content: name },
          },
        ],
      },
    },
  });
}

async function main() {

  if (!NOTION_TOKEN || NOTION_TOKEN.startsWith("YOUR_")) {

    console.error("Please set your NOTION_TOKEN (integration secret).");
    process.exit(1);
  }

  if (!DATABASE_ID || DATABASE_ID.startsWith("YOUR_")) {

    console.error("Please set your NOTION_DATABASE_ID.");
    process.exit(1);
  }

  for (const name of collection.reverse()) {

    try {
      await addRecord(name);
      console.log(`✔ Added: ${name}`);
    } catch (err) {
      console.error(`✘ Failed to add "${name}":`, err.body || err.message);
    }
  }

  console.log("Done.");
}

main();